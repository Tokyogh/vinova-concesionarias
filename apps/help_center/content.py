def manual(title: str, purpose: str, steps: list[str], cautions: list[str], checks: list[str]) -> str:
    sections = [
        title,
        "",
        "Objetivo",
        purpose,
        "",
        "Procedimiento recomendado",
    ]
    sections.extend(f"{index}. {step}" for index, step in enumerate(steps, start=1))
    sections.extend(["", "Controles importantes"])
    sections.extend(f"• {item}" for item in cautions)
    sections.extend(["", "Antes de terminar"])
    sections.extend(f"□ {item}" for item in checks)
    return "\n".join(sections)


